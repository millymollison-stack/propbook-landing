import { defineConfig } from 'vite';
import { readFileSync, writeFileSync, readdirSync, existsSync, copyFileSync } from 'fs';
import { join } from 'path';
import react from '@vitejs/plugin-react';

export default defineConfig({
  root: 'src',
  publicDir: '../public',
  base: process.env.VITE_BASE_PATH || '/',
  build: {
    rollupOptions: {
      output: {
        entryFileNames: 'assets/index.js',
        chunkFileNames: 'assets/[name].js',
        assetFileNames: 'assets/index.css',
      },
    },
  },
  plugins: [
    react(),
    {
      name: 'post-build-php',
      closeBundle() {
        const distDir = join(__dirname, 'src/dist');
        const indexHtml = join(distDir, 'index.html');
        const indexPhp = join(distDir, 'index.php');
        const assetsDir = join(distDir, 'assets');

        try {
          if (existsSync(indexHtml)) {
            copyFileSync(indexHtml, indexPhp);
            console.log('[post-build-php] index.html → index.php');
          } else {
            console.warn('[post-build-php] index.html not found, skipping PHP copy');
          }

          if (!existsSync(assetsDir)) {
            console.warn('[post-build-php] assets dir not found, skipping manifest');
            return;
          }

          const files = readdirSync(assetsDir);
          const jsFile = files.find(f => f.startsWith('index') && f.endsWith('.js')) || '';
          const cssFile = files.find(f => f.startsWith('index') && f.endsWith('.css')) || '';
          const builtAt = Date.now().toString();

          writeFileSync(join(distDir, 'assets-manifest.json'), JSON.stringify({ js: jsFile, css: cssFile, builtAt }, null, 2));
          console.log('[post-build] Asset manifest:', { js: jsFile, css: cssFile, builtAt });

          const versionTs = `// Auto-generated by vite post-build hook — do not edit manually
export const BUNDLE_JS = '${jsFile}';
export const BUNDLE_CSS = '${cssFile}';
export const BUNDLE_VERSION = '${builtAt}';
`;
          writeFileSync(join(__dirname, 'src/services/bundle-versions.ts'), versionTs);
          console.log('[post-build] Bundle versions written');

          // Also update SPA_TEMPLATE in siteDuplicationService.ts so the deployed bundle has correct URLs
          // Add cache-busting query string so Cloudflare/browsers always fetch the fresh file after deploy
          const sdsPath = join(__dirname, 'src/services/siteDuplicationService.ts');
          if (existsSync(sdsPath)) {
            let sds = readFileSync(sdsPath, 'utf8');
            sds = sds.replace(
              /<link rel="stylesheet" href="[^ "]*index\.css" \/>/,
              `<link rel="stylesheet" href="//propbook.pro/dev/assets/index.css?v=${builtAt}" />`
            );
            sds = sds.replace(
              /<script type="module" src="[^ "]*index(\-[A-Za-z0-9]+)?\.js"><\/script>/,
              `<script type="module" src="//propbook.pro/dev/assets/index.js?v=${builtAt}"></script>`
            );
            writeFileSync(sdsPath, sds);
            console.log('[post-build] SPA_TEMPLATE updated with JS=' + jsFile + ' CSS=' + cssFile + '?v=' + builtAt);
          }
        } catch (err) {
          console.error('[post-build-php] Error:', err);
        }
      }
    }
  ],
  optimizeDeps: {
    exclude: ['lucide-react'],
  },
});
